export function collectBooleanAttributeTokens(htmlAttributes, ariaAttributes) {
  const tokens = new Map();
  const globals = htmlAttributes.filter(row => row.elements.includes('HTML elements'));
  for (const { attribute, value } of [...globals, ...ariaAttributes]) {
    const keywords = value.map(keyword => keyword.replace(/^"(.*)"$/, '$1'));
    if (keywords.includes('true') && keywords.includes('false')) {
      tokens.set(attribute, 'true/false');
    } else if (keywords.includes('yes') && keywords.includes('no')) {
      tokens.set(attribute, 'yes/no');
    }
  }
  return tokens;
}

export default function buildBooleanAttributes(tokens) {
  const ariaNames = [];
  const trueFalse = [];
  const yesNo = [];
  for (const name of [...tokens.keys()].sort()) {
    if (!/^[a-z][a-z0-9-]*$/.test(name)) { throw new Error(`Invalid boolean attribute name: ${name}`); }
    if (tokens.get(name) === 'yes/no') {
      yesNo.push(`name === '${name}'`);
    } else if (name.startsWith('aria-')) {
      ariaNames.push(name.slice(5));
    } else {
      trueFalse.push(name);
    }
  }
  // Standard attribute names are safe regex alternatives. Share the ARIA prefix
  // to keep the generated pattern compact in the slim browser bundle.
  if (ariaNames.length) { trueFalse.unshift(`aria-(?:${ariaNames.join('|')})`); }
  const pattern = trueFalse.length ? new RegExp(`^(?:${trueFalse.join('|')})$`) : /(?!)/;
  const yesNoBranch = yesNo.length ? `  if (${yesNo.join(' || ')}) { return value ? 'yes' : 'no'; }\n` : '';

  return `// Generated by generate/bin/write-code-files.js — do not edit directly.
const BOOLEAN_TOKENS = ${pattern};

export function normalizeBooleanAttribute(name, value) {
  if (typeof value !== 'boolean') { return value; }
${yesNoBranch}  return BOOLEAN_TOKENS.test(name) ? String(value) : value;
}
`;
}
